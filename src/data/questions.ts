type SecondaryWeight = readonly [SinId, number];
const o = (text: string, signal: SinId, strength = 2.5, secondary?: SecondaryWeight): Option => ({
  text,
  signal,
  weights: { [signal]: strength, ...(secondary ? { [secondary[0]]: secondary[1] } : {}) },
});

